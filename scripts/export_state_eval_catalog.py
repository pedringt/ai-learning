"""Export State's controlled-eval scenario catalog for Project Health (#596).

Project Health explains a failed controlled eval from the scenario's contract: its synthetic Evidence or question,
the seeded Current State, the expected and acceptable outcomes, and the unsafe direction. The run record keeps only
the scenario ID, expected and observed outcome codes and failed-check names, so the page reads the rest from this
generated file. The scenarios are deliberately constructed test data that is already public in this repository; no
project, user or model-output content is exported.

Run from the repository root after changing a scenario file:

    python3 scripts/export_state_eval_catalog.py

state-project-complete/test_state_eval_catalog_export.py fails when state-eval-catalog.js is out of date.
"""
from __future__ import annotations

import dataclasses
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "state-eval-catalog.js"
sys.path.insert(0, str(ROOT / "state-project-complete"))

from eval.ask_quality_scenarios import SCENARIOS as ASK_SCENARIOS  # noqa: E402
from eval.review_interpretation_scenarios import SCENARIOS as REVIEW_SCENARIOS  # noqa: E402

SOURCES = {
    "review": "state-project-complete/eval/review_interpretation_scenarios.py",
    "ask": "state-project-complete/eval/ask_quality_scenarios.py",
}


def _plain(value):
    if isinstance(value, tuple):
        return [_plain(item) for item in value]
    return value


def _scenario(scenario) -> dict:
    return {field.name: _plain(getattr(scenario, field.name)) for field in dataclasses.fields(scenario)}


def catalog() -> dict:
    return {
        "sources": SOURCES,
        "review": [_scenario(item) for item in REVIEW_SCENARIOS],
        "ask": [_scenario(item) for item in ASK_SCENARIOS],
    }


def render() -> str:
    body = json.dumps(catalog(), indent=1, ensure_ascii=False)
    return (
        "// Generated by scripts/export_state_eval_catalog.py from State's eval scenario files. Do not edit by hand:\n"
        "// state-project-complete/test_state_eval_catalog_export.py fails when this file and the scenarios differ.\n"
        "// Synthetic controlled-eval test data only (#596); no project, user or model-output content.\n"
        "(function(root){\n"
        "  const catalog=" + body + ";\n"
        "  if(typeof module==='object'&&module.exports)module.exports=catalog;\n"
        "  if(root)root.STATE_EVAL_CATALOG=catalog;\n"
        "})(typeof window!=='undefined'?window:globalThis);\n"
    )


def main() -> None:
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(REVIEW_SCENARIOS)} review, {len(ASK_SCENARIOS)} ask scenarios)")


if __name__ == "__main__":
    main()
