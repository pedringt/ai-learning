#!/usr/bin/env python3
"""Generate the colour-literal section of site-dark.css (DEC-034).

The portfolio's light design uses tokens (--ink, --card, ...) plus a few hundred hard-coded colours
in the shared stylesheets and the pages' inline <style> blocks. site-dark.css remaps the tokens by
hand; this script covers the literals. It loads every portfolio page, walks every CSS rule the page
applies (CSSOM, so inline blocks are included), and for each colour literal in a background, border,
outline or text colour writes a dark counterpart scoped to html[data-theme="dark"].

The generated rules sit between the GENERATED markers in site-dark.css and are replaced on each run.
Hand-written fixes belong after the markers, where they win by source order.

Usage (serve the repo root first, e.g. python3 -m http.server 8204):
    python3 tools/dark_css.py http://127.0.0.1:8204          # rewrite site-dark.css
    python3 tools/dark_css.py http://127.0.0.1:8204 --check  # exit 1 if it would change
"""
import colorsys
import re
import sys
from pathlib import Path

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "site-dark.css"
BEGIN = "/* ---------- GENERATED by tools/dark_css.py: do not edit by hand ---------- */"
END = "/* ---------- END GENERATED ---------- */"

PAGES = ["index.html", "404.html", "ai-business-solutions-map.html", "ai-durable-knowledge.html",
         "ai-governance-handbook.html", "ai-power-user-playbook.html", "ai-professional-edge.html",
         "debugging-ai-systems.html", "implementation-context.html", "legal-ai-governance.html",
         "meridian.html", "project-health-case-study.html", "state-architecture-cost.html",
         "state-managed-agent-tracing.html", "state-testing-debugging.html", "tastemake.html"]
# The Library's standalone cheat sheets (own inline styles, no site header).
PAGES += sorted("cheat-sheets/" + p.name for p in (ROOT / "cheat-sheets").glob("*.html"))

# Rules for retired themes, and the dark sheet itself.
SKIP_SELECTOR = re.compile(r"\.dark\b|v88-dark|data-theme|prefers-color-scheme")
BG_PROPS = {"background-color", "background-image"}
BORDER_PROPS = {"border-top-color", "border-right-color", "border-bottom-color", "border-left-color",
                "outline-color", "column-rule-color"}
TEXT_PROPS = {"color", "text-decoration-color", "caret-color"}
# Site tokens remapped by hand at the top of site-dark.css; page-level tokens (--surface, --wash, ...) are generated.
HAND_TOKENS = {"--ink", "--muted", "--border", "--soft", "--softp", "--white", "--card", "--bg", "--purple",
               "--purple2", "--blue", "--cyan", "--green", "--gold", "--rd-pink", "--rd-line"}

COLLECT_JS = r"""
() => {
  const out = [];
  const props = %s;
  const walk = (rules, media) => {
    for (const r of rules) {
      if (r.type === 4) { walk(r.cssRules, [...media, '@media ' + r.conditionText]); continue; }
      if (r.type === 12) { walk(r.cssRules, [...media, '@supports ' + r.conditionText]); continue; }
      if (r.type !== 1) continue;
      const decl = {};
      for (let i = 0; i < r.style.length; i++) {
        const p = r.style[i];
        if (p.startsWith('--')) decl[p] = [r.style.getPropertyValue(p).trim(), r.style.getPropertyPriority(p)];
      }
      for (const p of props) {
        const v = r.style.getPropertyValue(p);
        if (v) decl[p] = [v, r.style.getPropertyPriority(p)];
      }
      if (Object.keys(decl).length) out.push({sel: r.selectorText, media, decl});
    }
  };
  for (const s of document.styleSheets) {
    if (s.href && s.href.includes('site-dark.css')) continue;
    try { walk(s.cssRules, []); } catch (e) {}
  }
  return out;
}
"""

# The dark card surface (#17141c), as hue/lightness/saturation, matching --card in site-dark.css.
SURFACE = colorsys.rgb_to_hls(0x17 / 255, 0x14 / 255, 0x1c / 255)

COLOR_RE = re.compile(r"rgba?\([^)]*\)|#[0-9a-fA-F]{3,8}\b|\b(white|black)\b")


def parse(tok):
    tok = tok.lower()
    if tok == "white":
        return 255, 255, 255, 1.0
    if tok == "black":
        return 0, 0, 0, 1.0
    if tok.startswith("#"):
        h = tok[1:]
        if len(h) in (3, 4):
            h = "".join(c * 2 for c in h)
        a = int(h[6:8], 16) / 255 if len(h) == 8 else 1.0
        return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), a
    nums = [float(x) for x in re.split(r"[\s,/]+", tok[tok.index("(") + 1:-1].strip()) if x]
    return nums[0], nums[1], nums[2], (nums[3] if len(nums) > 3 else 1.0)


def fmt(h, l, s, a):
    r, g, b = (round(c * 255) for c in colorsys.hls_to_rgb(h, l, s))
    return f"rgb({r} {g} {b})" if a >= 0.999 else f"rgb({r} {g} {b} / {round(a, 3)})"


# The bright product-art palette (acid, cyan, lilac, rose, amber, pinks): these fills keep their look in
# both themes, and text on them stays dark.
ACCENTS = ["f4ff52", "f6ee52", "8fe9f4", "cfc7ff", "ffb3d6", "ffe174", "00bfd6", "ff5fa2", "f0408f",
           "ee2a7b", "6b5cff", "ff6b57"]
ACCENT_RGB = [tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) for h in ACCENTS]
ACCENT_VARS = re.compile(r"var\(--(acid|rd-acid|rd-cyan|rd-pink|rd-pink-soft|rd-violet|rd-coral|cc-accent|cc-acid|"
                         r"cc-cyan|cc-lilac|lilac|rose|yellow|pink)\)")
INK = "rgb(21 17 26)"
OFFSET_INK = re.compile(r"-?\d+px -?\d+px 0(px)? var\(--(cc-)?ink\)")
INK_VAR = re.compile(r"var\(--(cc-)?ink\)")
DARK_SHADOW = "rgb(0 0 0 / 0.6)"


def is_accent(r, g, b):
    return any(abs(r - x) + abs(g - y) + abs(b - z) <= 12 for x, y, z in ACCENT_RGB)


def map_bg(tok):
    r, g, b, a = parse(tok)
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    if is_accent(r, g, b) or a == 0:
        return None
    if l > 0.85 and s < 0.2:           # white / near-white surfaces become the dark card surface
        return fmt(*SURFACE, a)
    if l > 0.85:                       # pale tints keep their hue
        return fmt(h, 0.15, min(s, 1) * 0.35, a)
    if l > 0.65:                       # light pastel chips
        return fmt(h, 0.24, s * 0.5, a)
    if l < 0.16 and s < 0.35:          # ink-filled buttons and badges invert
        return fmt(h, 0.92, s * 0.6, a)
    return None


def map_border(tok):
    r, g, b, a = parse(tok)
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    if is_accent(r, g, b) or a == 0 or l <= 0.6:
        return None
    return fmt(h, 0.2 + (1 - l) * 0.3, s * 0.35, a)


def map_text(tok):
    """Dark text gets lighter. Ink-filled buttons (white text on var(--ink)) are fixed by hand in site-dark.css."""
    r, g, b, a = parse(tok)
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    if l >= 0.6:
        return None
    return fmt(h, max(0.95 - 0.7 * l, 0.7 if s > 0.35 else 0.0), s, a)


def map_token(tok):
    """A page-level colour token: light values are surfaces or tints, dark ones are text or accents."""
    r, g, b, a = parse(tok)
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    if l > 0.65:
        return map_bg(tok)
    return map_text(tok)


def remap(value, fn):
    changed = False

    def sub(m):
        nonlocal changed
        new = fn(m.group(0))
        if new is None:
            return m.group(0)
        changed = True
        return new
    out = COLOR_RE.sub(sub, value)
    return out if changed else None


def keeps_accent_fill(decl):
    v = decl.get("background", ["", ""])[0] + " " + decl.get("background-color", ["", ""])[0]
    if ACCENT_VARS.search(v):
        return True
    for m in COLOR_RE.finditer(v):
        r, g, b, a = parse(m.group(0))
        if a > 0.5 and is_accent(r, g, b):
            return True
    return False


def scope(selector):
    """Scope to dark mode without changing specificity, so the original cascade still decides:
    a rule overridden by a more specific one in light mode stays overridden in dark mode."""
    parts = []
    for sel in split_selectors(selector):
        sel = sel.strip()
        if sel.startswith(":root"):
            parts.append(':root:where([data-theme="dark"])' + sel[len(":root"):])
        elif re.match(r"html\b", sel):
            parts.append('html:where([data-theme="dark"])' + sel[4:])
        else:
            parts.append(':where(html[data-theme="dark"]) ' + sel)
    return ",\n".join(parts)


def split_selectors(selector):
    out, depth, cur = [], 0, ""
    for ch in selector:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return out


def build(base):
    rules = {}   # (media tuple, selector) -> {prop: value}
    order = []
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page()
        props = sorted(BG_PROPS | BORDER_PROPS | TEXT_PROPS | {"background", "box-shadow"})
        for name in PAGES:
            page.goto(f"{base}/{name}", wait_until="networkidle")
            for r in page.evaluate(COLLECT_JS % str(props)):
                if SKIP_SELECTOR.search(r["sel"]) or any(SKIP_SELECTOR.search(m) for m in r["media"]):
                    continue
                decl = r["decl"]
                accent_fill = keeps_accent_fill(decl)
                out = {}
                for prop, (value, prio) in decl.items():
                    if prop == "box-shadow":
                        # Offset "paper" shadows in ink (3px 3px 0 var(--cc-ink)) turn light with the ink token;
                        # keep them dark (Paige, Nov 23).
                        if OFFSET_INK.search(value):
                            out[prop] = (INK_VAR.sub(DARK_SHADOW, value), prio)
                        continue
                    if prop == "background":
                        # With var() inside, the longhands come back empty, so remap the shorthand as written.
                        if "var(" not in value:
                            continue
                        new = remap(value, map_bg)
                        if new:
                            out[prop] = (new, prio)
                        continue
                    if prop.startswith("--"):
                        new = None if prop in HAND_TOKENS else remap(value, map_token)
                    elif prop in BG_PROPS:
                        new = remap(value, map_bg)
                    elif prop in BORDER_PROPS:
                        new = remap(value, map_border)
                    elif accent_fill:
                        new = None
                    else:
                        new = remap(value, map_text)
                    if new:
                        out[prop] = (new, prio)
                if accent_fill:
                    # dark text on accent fills, children included
                    star = ", ".join(x.strip() + " *" for x in split_selectors(r["sel"]) if "::" not in x)
                    out["color"] = (INK, "important")
                    if star:
                        k2 = (tuple(r["media"]), star)
                        if k2 not in rules:
                            rules[k2] = {}
                            order.append(k2)
                        rules[k2]["color"] = (INK, "important")
                if not out:
                    continue
                key = (tuple(r["media"]), r["sel"])
                if key not in rules:
                    rules[key] = {}
                    order.append(key)
                rules[key].update(out)
        browser.close()

    lines = [BEGIN]
    for media, sel in order:
        body = "".join(f"  {p}:{v}{' !important' if prio else ''};\n"
                       for p, (v, prio) in sorted(rules[(media, sel)].items()))
        block = f"{scope(sel)}{{\n{body}}}"
        for m in reversed(media):
            block = f"{m}{{\n{block}\n}}"
        lines.append(block)
    lines.append(END)
    return "\n".join(lines)


def main():
    base = sys.argv[1].rstrip("/")
    generated = build(base)
    current = OUT.read_text()
    if BEGIN in current:
        head, rest = current.split(BEGIN, 1)
        tail = rest.split(END, 1)[1]
        new = head + generated + tail
    else:
        new = current.rstrip() + "\n\n" + generated + "\n"
    if "--check" in sys.argv:
        sys.exit(0 if new == current else 1)
    OUT.write_text(new)
    print(f"site-dark.css: {generated.count('{') - generated.count('@')} generated rules")


if __name__ == "__main__":
    main()
