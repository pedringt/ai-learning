// DEC-034: every portfolio page sets its theme before first paint and loads the dark sheet last.
// site-theme.js must come before the first stylesheet (no light flash in dark mode), and site-dark.css must be
// the last stylesheet in <head>, after any inline <style> block, or an equal-specificity light rule wins.
const fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..');
let pass=0,fail=0;
function check(name,ok,detail=''){if(ok){pass++;console.log('ok',name)}else{fail++;console.error('FAIL',name,detail)}}

// Portfolio pages = root pages on the shared stylesheet. project-health.html and state-evals.html are out of scope.
const pages=fs.readdirSync(root).filter(f=>f.endsWith('.html')).filter(f=>/site-components\.css/.test(fs.readFileSync(path.join(root,f),'utf8')));
check('the portfolio has its 16 pages',pages.length===16,pages.length+' pages');

for(const page of pages){
  const html=fs.readFileSync(path.join(root,page),'utf8');
  const head=html.slice(0,html.indexOf('</head>'));
  const themeAt=head.search(/<script src="\/?site-theme\.js"><\/script>/);
  const firstSheet=head.search(/<link[^>]*\.css/);
  check(`${page}: site-theme.js loads before the first stylesheet`,themeAt>=0&&themeAt<firstSheet);
  const darkAt=head.search(/<link href="\/?site-dark\.css" rel="stylesheet">/);
  const after=darkAt>=0?head.slice(darkAt+1):'';
  check(`${page}: site-dark.css is the last stylesheet in <head>`,darkAt>=0&&!/<link[^>]*\.css|<style/.test(after));
}

// The Library's cheat sheets: own inline styles and no site header, so the script names the toggle's spot (.bar).
const sheets=fs.readdirSync(path.join(root,'cheat-sheets')).filter(f=>f.endsWith('.html'));
check('the Library has its 17 cheat sheets',sheets.length===17,sheets.length+' sheets');
for(const sheet of sheets){
  const html=fs.readFileSync(path.join(root,'cheat-sheets',sheet),'utf8');
  const head=html.slice(0,html.indexOf('</head>'));
  const themeAt=head.search(/<script src="\.\.\/site-theme\.js" data-toggle-host="\.bar"><\/script>/);
  check(`cheat-sheets/${sheet}: site-theme.js loads before its styles, with the toggle in .bar`,themeAt>=0&&themeAt<head.indexOf('<style')&&/class="bar"/.test(html));
  const darkAt=head.search(/<link href="\.\.\/site-dark\.css" rel="stylesheet">/);
  check(`cheat-sheets/${sheet}: site-dark.css is the last stylesheet in <head>`,darkAt>=0&&!/<link[^>]*\.css|<style/.test(head.slice(darkAt+1)));
}
const theme=fs.readFileSync(path.join(root,'site-theme.js'),'utf8');
check('printing always uses the light theme',/beforeprint[\s\S]*'light'/.test(theme)&&/afterprint/.test(theme));

const ignore=fs.readFileSync(path.join(root,'.vercelignore'),'utf8');
check('the site serves root .js and .css files (site-theme.js, site-dark.css)',/^!\/\*\.js$/m.test(ignore)&&/^!\/\*\.css$/m.test(ignore));

const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
check('index.html no longer forces light mode',!/setTheme\(false\)/.test(index));
const dark=fs.readFileSync(path.join(root,'site-dark.css'),'utf8');
check('site-dark.css has its generated section',dark.includes('GENERATED by tools/dark_css.py')&&dark.includes('END GENERATED'));

// site-dark.css is shared, so the cheat sheets' own inline rules must stay on the cheat sheets. Their
// .lead{background:#f8f7ff} callout once tinted every portfolio intro (.lead) in dark mode, and their
// table rules striped the portfolio's tables. Every cheat sheet carries the marker the generator scopes to.
for(const sheet of sheets){
  const html=fs.readFileSync(path.join(root,'cheat-sheets',sheet),'utf8');
  check(`${sheet}: marked <html data-cheat-sheet>`,/<html[^>]*\bdata-cheat-sheet\b/.test(html));
}
const generated=dark.slice(dark.indexOf('GENERATED by tools/dark_css.py'),dark.indexOf('END GENERATED'));
for(const sel of ['.lead','thead','tr:nth-child(2n)','body','.note','.label']){
  const global=new RegExp(':where\\(html\\[data-theme="dark"\\]\\) '+sel.replace(/[.()]/g,'\\$&')+'\\{');
  check(`site-dark.css: the cheat sheets' ${sel} rule is not applied site-wide`,!global.test(generated));
}

console.log(`\n${pass} passed, ${fail} failed`);
if(fail)process.exit(1);
